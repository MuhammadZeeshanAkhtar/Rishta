/**
 * A deep link the router can safely parse, or the home screen.
 *
 * Expo Router reads an incoming link's query with `query-string`, which decodes it with
 * `decode-uri-component` 0.2.2. That version takes exponential time on malformed
 * percent-encoding (GHSA-qr28-fpjm-wq7f, GHSA-vcc3-ghjq-m6fr): about 600 characters
 * freeze the app for seconds, a little more for minutes. The fixed versions are
 * ES-module only and `query-string` 7 cannot load them, so the dependency cannot be
 * upgraded yet (docs/PRODUCTION_SECURITY.md).
 *
 * Every link this app receives (the email callback, a family invitation, Supabase's own
 * error redirects) is generated by software, so it is never malformed and never long. A
 * link that is either goes to the home screen instead of the parser. Each part is
 * checked with the platform's own decoder, which is linear.
 */

/** Far above any real link (the longest, a sign-in callback, is a few hundred). */
export const MAX_DEEP_LINK_LENGTH = 4096;

export function safeSystemPath(path: string): string {
  if (typeof path !== 'string' || path.length > MAX_DEEP_LINK_LENGTH) return '/';
  const queryStart = path.indexOf('?');
  if (queryStart === -1) return path;
  const hashStart = path.indexOf('#', queryStart);
  const query = path.slice(queryStart + 1, hashStart === -1 ? undefined : hashStart);
  for (const part of query.split(/[&=]/)) {
    try {
      decodeURIComponent(part.replace(/\+/g, ' '));
    } catch {
      return '/';
    }
  }
  return path;
}
